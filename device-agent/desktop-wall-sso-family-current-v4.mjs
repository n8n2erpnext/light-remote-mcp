/**
 * T04b9c2 — Device Agent private live Owner-family verification adapter.
 *
 * Pass verifyLiveOwnerFamily to the existing Local Wall SSO session ONLY
 * from a trusted, enabled Device Agent after secure bootstrap acceptance.
 * It makes a fresh enrolled Ed25519 request on EVERY protected Wall request.
 * No browser/React route, A/B grant, token, cookie or dynamic URL.
 * Source-only: operator-agent.mjs does not mount this callback yet.
 */
export const GOLDABV2_WALL_SSO_FAMILY_URL_V4=
  'https://goldabv2.light-remote.thaiduy.digital/device-channel/desktop-wall-sso-family-current';
import {WALL_SSO_FAMILY_CURRENT_ACTION_V4}
  from '../operator-host/desktop-wall-sso-family-current-v4.mjs';

const ID=/^[A-Za-z0-9._:-]{1,160}$/;
const ACCOUNT=/^[A-Za-z0-9._:-]{1,128}$/;
const FAMILY=/^[A-Za-z0-9_-]{43}$/;
const NONCE=/^[A-Za-z0-9_-]{16,128}$/;
const SIG=/^[A-Za-z0-9_-]{64,128}$/;
const exact=(v,names)=>v&&typeof v==='object'&&!Array.isArray(v)&&
  Object.keys(v).length===names.length&&
  Object.keys(v).every(k=>names.includes(k));
const valid=(re,v)=>typeof v==='string'&&re.test(v);
const MAX_BYTES=2048;

export function createDesktopWallSsoAgentFamilyCurrentV4({
  readEnrollment,signChannel,fetchImpl=fetch,clock=Date.now
}={}){
  if(typeof readEnrollment!=='function'||typeof signChannel!=='function'||
     typeof fetchImpl!=='function'||typeof clock!=='function')
    throw Error('desktop_wall_sso_family_adapter_unavailable');

  async function verifyLiveOwnerFamily(input){
    // Fail closed; don't surface private details to the browser or logs.
    try{
      if(!exact(input,['accountId','deviceId','familyId'])||
         !valid(ACCOUNT,input.accountId)||!valid(ID,input.deviceId)||
         !valid(FAMILY,input.familyId))return false;
      const before=readEnrollment();
      if(before?.revoked===true||before?.accountId!==input.accountId||
         before?.deviceId!==input.deviceId)return false;
      // New nonce generated by existing signedChannelEnvelope for every call.
      const envelope=await signChannel(
        WALL_SSO_FAMILY_CURRENT_ACTION_V4,
        Object.freeze({...input})
      );
      const now=clock();
      if(!Number.isSafeInteger(now)||
         !exact(envelope,['deviceId','timestamp','nonce','signature','payload'])||
         envelope.deviceId!==input.deviceId||
         !Number.isSafeInteger(envelope.timestamp)||
         Math.abs(now-envelope.timestamp)>60_000||
         !valid(NONCE,envelope.nonce)||!valid(SIG,envelope.signature)||
         !exact(envelope.payload,['accountId','deviceId','familyId'])||
         envelope.payload.accountId!==input.accountId||
         envelope.payload.deviceId!==input.deviceId||
         envelope.payload.familyId!==input.familyId)
        return false;
      const body=JSON.stringify(envelope);
      if(Buffer.byteLength(body)>MAX_BYTES)return false;
      const response=await fetchImpl(GOLDABV2_WALL_SSO_FAMILY_URL_V4,{
        method:'POST',
        headers:{'content-type':'application/json','accept':'application/json'},
        body,redirect:'error',credentials:'omit',
        referrerPolicy:'no-referrer',cache:'no-store',
        signal:AbortSignal.timeout(8000)
      });
      if(response?.status!==200||response?.ok!==true||
         response.redirected===true||
         !String(response.headers?.get('content-type')||'')
           .toLowerCase().startsWith('application/json')||
         Number(response.headers?.get('content-length')||0)>MAX_BYTES||
         !response.body||
         typeof response.body[Symbol.asyncIterator]!=='function')
        return false;
      let total=0;
      const chunks=[];
      for await(const part of response.body){
        total+=part.length;
        if(total>MAX_BYTES)return false;
        chunks.push(Buffer.from(part));
      }
      const value=JSON.parse(Buffer.concat(chunks,total).toString('utf8'));
      if(!exact(value,['ok','current','deviceId'])||
         value.ok!==true||value.current!==true||
         value.deviceId!==input.deviceId)return false;
      // A relink during network await cannot keep the old Owner login.
      const after=readEnrollment();
      return after?.revoked!==true&&
        after?.accountId===input.accountId&&
        after?.deviceId===input.deviceId;
    }catch{return false}
  }
  return Object.freeze({verifyLiveOwnerFamily});
}
