import assert from 'node:assert/strict';
import {FleetRouter,FleetError} from '../../operator-host/fleet-router.mjs';

let now=1_900_000_000_000;
const events=[];
const fleet=new FleetRouter({now:()=>now,emit:e=>events.push(e),channelTtlMs:6000,commandLeaseMs:2500});
const owner={accountId:'gold-g3-acct',deviceId:'gold-g3-device',nodeId:'gold-g3-node'};
const poll=()=>fleet.poll({...owner,sessionCeiling:2,capabilities:['filesystem'],draining:false});
const first=poll();
assert.equal(first.node.state,'online');
const cmd=fleet.enqueue({...owner,jobId:'g3_initial_job',payload:{type:'g3-probe'}});
const dispatched=poll();
assert.equal(dispatched.command.commandId,cmd.commandId);
assert.equal(dispatched.command.attempts,1);
now+=6500;
const stale=fleet.view(owner.nodeId);
assert.equal(stale.inFlightCommands,1,'do not lose existing dispatched work');
assert.equal(stale.state,'offline','in-flight command must not impersonate live channel');
assert.equal(stale.channelFresh,false,'authenticated channel TTL must be decisive');
assert.equal(stale.dispatchReady,false);
assert.equal(stale.readinessReason,'channel_stale');
assert.throws(()=>fleet.enqueue({...owner,jobId:'g3_stale_job',payload:{type:'new-work'}}),e=>e instanceof FleetError&&e.message==='target_node_offline');
assert.equal(fleet.view(owner.nodeId).queuedCommands,0,'rejected command cannot enter queue');
console.log('G3_STALE_INFLIGHT_CHANNEL_NOT_ONLINE=PASS');
console.log('G3_STALE_DISPATCH_BLOCKED_NO_QUEUE=PASS');
const resumed=poll();
assert.equal(resumed.node.channelFresh,true);
assert.equal(resumed.command.commandId,cmd.commandId,'original in-flight command remains available');
assert.equal(resumed.command.attempts,2,'lease-driven redelivery survives stale gap');
assert.equal(resumed.node.dispatchReady,true);
fleet.complete({...owner,commandId:cmd.commandId});
assert.equal(fleet.view(owner.nodeId).inFlightCommands,0);
const next=fleet.enqueue({...owner,jobId:'g3_after_reconnect',payload:{}});
assert.ok(next.commandId);
console.log('G3_AUTHENTICATED_REPOLL_REDELIVERY_RECOVERS=PASS');
fleet.setOwnerDrain(owner.nodeId,true);
assert.equal(fleet.view(owner.nodeId).channelFresh,true);
assert.equal(fleet.view(owner.nodeId).dispatchReady,false);
assert.equal(fleet.view(owner.nodeId).readinessReason,'draining');
assert.throws(()=>fleet.assertRoutable(owner.nodeId,owner),/target_node_draining/);
fleet.setOwnerDrain(owner.nodeId,false);
assert.equal(fleet.view(owner.nodeId).dispatchReady,true);
now+=7000;
assert.equal(fleet.view(owner.nodeId).state,'offline');
assert.equal(fleet.view(owner.nodeId).readinessReason,'channel_stale');
assert.throws(()=>fleet.assertRoutable(owner.nodeId,{accountId:'other-owner'}),/target_node_account_mismatch/);
console.log('G3_DRAIN_OWNER_AND_FRESHNESS_GUARDS=PASS');
