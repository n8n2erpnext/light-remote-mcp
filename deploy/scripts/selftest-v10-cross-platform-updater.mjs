import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve(new URL('../..',import.meta.url).pathname);
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const winProgram=read('client/windows-native/LightRemote.Updater/Program.cs');
const winApply=read('client/windows-native/LightRemote.Updater/UpdateApplier.cs');
const winInstaller=read('client/windows-native/installer/GptOperator.iss');
const winWorkflow=read('.github/workflows/windows-native-client.yml');
const winTask=read('device-agent/install-windows-task.ps1');
const macUpdater=read('client/macos/updater.mjs');
const macPlist=read('client/macos/launchd/com.lightremote.updater.plist');
const macAgent=read('client/macos/launchd/com.lightremote.agent.plist');
const macPkg=read('client/macos/build-pkg.sh');
const linuxInstall=read('client/linux/install.sh');
assert.ok(winProgram.includes('--check-update')&&winProgram.includes('--apply-update-now'),'windows_owner_update_modes_missing');
assert.ok(winApply.includes('WaitForCoreAckAsync')&&winApply.includes('FinalizeHelperCandidateAsync'),'windows_two_phase_gate_missing');
assert.ok(winWorkflow.includes("helper-candidate"),'windows_helper_candidate_missing');
assert.ok(!winInstaller.includes('UpdaterStageDir'),'windows_duplicate_helper_payload_remains');
assert.ok(winTask.includes('if(-not(Test-Path $Updater))')&&winTask.includes("$HelperCandidate=Join-Path $InstallRoot 'helper-candidate'")&&winTask.includes("Copy-Item (Join-Path $HelperCandidate '*') $UpdaterRoot -Recurse -Force"),'windows_helper_bootstrap_must_not_overwrite');
assert.ok(macUpdater.includes('waitForCoreAck')&&macUpdater.includes('finalizeHelperFromCore'),'mac_two_phase_gate_missing');
assert.ok(macPlist.includes('/updater/current/runtime/node')&&macPlist.includes('<key>WatchPaths</key>'),'mac_lifeboat_launchd_missing');
assert.ok(macAgent.includes('LIGHT_REMOTE_UPDATE_STATE_DIR'),'mac_core_update_state_missing');
assert.ok(macPkg.includes('if [[ ! -x "\\$ROOT/updater/current/runtime/node" ]]'),'mac_helper_bootstrap_not_guarded');
assert.ok(linuxInstall.includes('gpt-operator-agent-update-check.service')&&linuxInstall.includes('gpt-operator-agent-update.path'),'linux_check_apply_split_missing');
assert.ok(linuxInstall.includes('AGENT_WAS_ACTIVE=0')&&linuxInstall.includes('systemctl restart gpt-operator-device-agent.service'),'linux_existing_agent_restart_missing');
assert.ok(linuxInstall.includes('systemctl show gpt-operator-device-agent.service --property=Environment --value')&&linuxInstall.includes('WALL_DISPLAY_HOST'),'linux_effective_wall_url_missing');
console.log('v10-cross-platform-updater-lifeboat=PASS');
