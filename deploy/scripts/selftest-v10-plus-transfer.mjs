import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { ChunkTransferRegistry } from '../../gateway/chunk-transfer.mjs';
import { createPlusTransferHandlers } from '../../gateway/plus-transfer.mjs';

const sha=value=>crypto.createHash('sha256').update(value).digest('hex');
const response=()=>({statusCode:200,body:null,status(n){this.statusCode=n;return this;},json(v){this.body=v;return this;}});
const clientSessionId='acs_transfer_selftest_0001';
const agentId='agent-transfer-selftest-0001';
const deviceId='dev_transfer_selftest';
const nodeId='node-transfer-selftest';
const grantId='dag_transfer_selftest_0001';
const req=(body={},id=null)=>({body,params:id?{id}:{},plusClient:{clientSessionId,agentId},plusClientDeviceId:deviceId,plusClientDevice:{device:{nodeId},grant:{grantId}}});

let failCommit=true,captured=null;
const registry=new ChunkTransferRegistry({maxTransferBytes:1024*1024,maxChunkBytes:5120});
const handlers=createPlusTransferHandlers({registry,sealOperatorPayload:payload=>({sealed:payload}),callOperatorJson:async(method,path,body)=>{captured={method,path,body};if(failCommit){const e=new Error('operator_down');e.status=502;throw e;}return {ok:true,data:{accepted:true}};}});
const payload={action:'fs',operationId:'transfer-operation-0001',sessionId:'session-transfer-0001',agentId:'attacker-agent-0001',nodeId:'attacker-node',fs:{op:'write',path:'/tmp/large.txt',content:'X'.repeat(24000)}};
const raw=Buffer.from(JSON.stringify(payload));
assert.ok(raw.length>12000,'test_payload_must_exceed_legacy_get_cap');
const chunkBytes=4096,totalChunks=Math.ceil(raw.length/chunkBytes);
let r=response();
handlers.begin(req({purpose:'operator-payload',totalBytes:raw.length,totalChunks,sha256:sha(raw)}),r);
assert.equal(r.statusCode,200);
const transferId=r.body.transfer.id;
for(let index=totalChunks-1;index>=0;index--){
  const start=index*chunkBytes,end=Math.min(raw.length,(index+1)*chunkBytes);
  const chunk=raw.subarray(start,end);
  r=response();
  handlers.put(req({index,data:chunk.toString('base64url'),sha256:sha(chunk)},transferId),r);
  assert.equal(r.statusCode,200);
}
r=response();handlers.status(req({},transferId),r);
assert.equal(r.body.transfer.complete,true);
r=response();
await handlers.commit(req({},transferId),r);
assert.equal(r.statusCode,502);
assert.equal(r.body.error,'operator_down');
assert.equal(registry.view({clientSessionId,agentId,deviceId},transferId).complete,true);
failCommit=false;
r=response();
await handlers.commit(req({},transferId),r);
assert.equal(r.statusCode,200);
assert.equal(captured.method,'POST');
assert.equal(captured.path,'/v1/device-access/execute');
assert.equal(captured.body.grantId,grantId);
const sealed=captured.body.envelope.sealed;
assert.equal(sealed.agentId,agentId);
assert.equal(sealed.nodeId,nodeId);
assert.notEqual(sealed.agentId,payload.agentId);
assert.notEqual(sealed.nodeId,payload.nodeId);
assert.throws(()=>registry.view({clientSessionId,agentId,deviceId},transferId),/transfer_not_found/);
console.log('v10-plus-transfer-large-payload-retry=PASS');
console.log('v10-plus-transfer-auth-identity-override=PASS');
const compatChunk=Buffer.alloc(5120,7);
const compatPayload={deviceId,transferId:'lt_compatibility_selftest_0001',index:0,data:compatChunk.toString('base64url'),sha256:sha(compatChunk)};
const compatEncoded=Buffer.from(JSON.stringify(compatPayload)).toString('base64url');
assert.ok(compatEncoded.length<12000,`compat_chunk_exceeds_12k:${compatEncoded.length}`);
const oversized=Buffer.alloc(8192,7);
const oversizedEncoded=Buffer.from(JSON.stringify({...compatPayload,data:oversized.toString('base64url'),sha256:sha(oversized)})).toString('base64url');
assert.ok(oversizedEncoded.length>12000,'oversized_chunk_should_exceed_legacy_cap');
console.log('v10-plus-transfer-5k-compat-cap=PASS');
