import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {normalizeDesktopInput}=require('../../lib/real-remote-input.cjs');
const bridge=fs.readFileSync(new URL('../../lib/native-desktop.mjs',import.meta.url),'utf8');
const swift=fs.readFileSync(new URL('../../client/macos/real-remote/main.swift',import.meta.url),'utf8');
const typed=normalizeDesktopInput({events:[{type:'type',text:'Claude123 test',intervalMs:60,guardTitleContains:'Google Chrome'}]},{platform:'darwin'});
assert.deepEqual(typed.events,[{type:'type',text:'Claude123 test',intervalMs:60,guardTitleContains:'Google Chrome'}]);
assert.throws(()=>normalizeDesktopInput({events:[{type:'type',text:'abc'}]},{platform:'win32'}),/macos_only/);
assert.throws(()=>normalizeDesktopInput({events:[{type:'type',text:'Viet Nam đã'}]},{platform:'darwin'}),/ascii_only/);
assert.throws(()=>normalizeDesktopInput({events:[{type:'type',text:'a'.repeat(321)}]},{platform:'darwin'}),/invalid_physical_text/);
assert.match(bridge,/type==='type'/);
assert.match(bridge,/op:'text\.type'/);
assert.match(swift,/case "text\.type":/);
assert.match(swift,/hid-key-by-key-verified/);
assert.match(swift,/physical_keyboard_readback_mismatch/);
assert.match(swift,/let expectedText=before\+value/);
assert.match(swift,/usleep\(down \? 8500 : 4500\)/);
assert.match(swift,/usleep\(25000\)/);
console.log('macos-physical-type-route=PASS');
console.log('windows-type-fail-closed=PASS');
console.log('native-keyboard-pace-and-readback-contract=PASS');
