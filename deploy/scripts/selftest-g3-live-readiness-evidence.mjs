import assert from 'node:assert/strict';
import {evaluateGoldG3Readiness} from './uat-gold-g3-readiness-audit.mjs';
const node=(o={})=>({mode:'outbound-leaf',channelFresh:true,dispatchReady:true,executorReady:true,...o});
let report=evaluateGoldG3Readiness({nodes:[{mode:'local'},node({executorReady:undefined})],sourceParity:false});
assert.equal(report.gate,'BLOCKED_OPERATOR_SOURCE_MISMATCH');
assert.equal(report.unknownOnFreshChannels,1);
assert.equal(report.optimisticAdmissionWithoutExecutorProof,1);
console.log('G3_LEGACY_FRESH_CHANNEL_NOT_EXECUTOR_PROOF=PASS');
report=evaluateGoldG3Readiness({nodes:[node({executorReady:false})],sourceParity:true});
assert.equal(report.gate,'FAIL_ROUTING_SAFETY');
assert.equal(report.unsafeExecutorFalseAdmission,1);
console.log('G3_FLEET_REJECTS_FALSE_EXECUTOR_ADMISSION=PASS');
report=evaluateGoldG3Readiness({nodes:[node({channelFresh:false})],sourceParity:true});
assert.equal(report.gate,'FAIL_ROUTING_SAFETY');
console.log('G3_FLEET_REJECTS_STALE_CHANNEL_ADMISSION=PASS');
report=evaluateGoldG3Readiness({nodes:[node(),node({executorReady:false,dispatchReady:false})],sourceParity:true});
assert.equal(report.gate,'SOURCE_AND_FLEET_EVIDENCE_PRESENT');
assert.equal(report.unknownOnFreshChannels,0);
console.log('G3_FLEET_REQUIRES_EXPLICIT_EXECUTOR_SIGNAL=PASS');
