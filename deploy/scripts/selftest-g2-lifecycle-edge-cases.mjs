import assert from 'node:assert/strict';
import os from 'node:os';
import {NativeProcessRegistry} from '../../lib/native-process.mjs';
import {NativeTerminalRegistry} from '../../lib/native-terminal.mjs';

const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const owner={accountId:'g2acct',deviceId:'g2dev',sessionId:'g2session',agentId:'g2agent'};
const spawnSpec=script=>({file:process.execPath,args:['-e',script]});
const reg=new NativeProcessRegistry({maxProcesses:2,bufferBytes:65536,stopGraceMs:125});
const awaitState=async(id,expect,ms=2000)=>{const until=Date.now()+ms;while(Date.now()<until){const row=reg.view(id,owner);if(expect(row))return row;await sleep(15);}throw new Error('G2_STATE_TIMEOUT '+JSON.stringify(reg.view(id,owner)));};
const wrong={...owner,agentId:'other-g2agent'};
const bad=reg.start({...owner,script:'',cwd:os.tmpdir(),spawnSpec:()=>({file:'/__g2_no_such_executable__',args:[]})});
const failure=await awaitState(bad.processId,row=>row.finishedAt!=null);
assert.equal(failure.state,'error');assert.equal(failure.exitCode,127);
assert.ok(reg.output(bad.processId,owner,{stream:'stderr'}).output.text.length>0);
console.log('G2_PROCESS_INVALID_SPAWN_TYPED_STATE=PASS');
const ring=reg.start({...owner,cwd:os.tmpdir(),script:"require('fs').writeSync(1,Buffer.alloc(1024*512,88))",spawnSpec});
await awaitState(ring.processId,row=>row.finishedAt!=null);
const output=reg.output(ring.processId,owner,{offset:0,limit:32000}).output;
assert.equal(output.totalBytes,524288);
assert.equal(output.truncatedBefore,true);assert.ok(output.baseOffset>=458752);
assert.ok(output.returnedBytes<=32000);assert.ok(output.hasMore);
assert.throws(()=>reg.output(ring.processId,wrong),/process_owner_mismatch/);
console.log('G2_PROCESS_BYTE_RING_GAP_AND_OWNER=PASS');
const timeout=reg.start({...owner,cwd:os.tmpdir(),timeoutMs:160,script:"process.on('SIGTERM',()=>{});console.log('G2_TIMED_READY');setInterval(()=>{},1000);",spawnSpec});
await awaitState(timeout.processId,r=>r.stdoutBytes>=10);
const limit=await awaitState(timeout.processId,row=>row.finishedAt!=null,7500);
assert.equal(limit.state,'timeout');assert.equal(limit.timedOut,true);
console.log('G2_PROCESS_TIMEOUT_SIGKILL_FINAL_STATE=PASS');
let clock=Date.now();
let killed=0,exists=false;
const fakeProvider={spawn(){exists=true;return{pid:null,write(){},resize(){},onData(){},onExit(){},kill(){killed++;exists=false;}};}};
const terminal=new NativeTerminalRegistry({ptyProvider:fakeProvider,platform:'linux',now:()=>clock,idleTtlMs:60000,hardTtlMs:90000});
const t=terminal.start({...owner,cwd:os.tmpdir(),shellSpec:{file:'/bin/sh',args:[],shell:'sh'}});
assert.throws(()=>terminal.output(t.terminalId,wrong),/terminal_owner_mismatch/);
clock+=90001;terminal.prune();assert.ok(killed>0,'terminal hard TTL initiates kill');
assert.equal(terminal.view(t.terminalId,owner).state,'expired');
terminal.close();
console.log('G2_TERMINAL_HARD_TTL_OWNER=PASS');
