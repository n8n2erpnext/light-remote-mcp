import assert from 'node:assert/strict';
import { ChunkTransferRegistry, sha256Hex } from '../../gateway/chunk-transfer.mjs';

const owner={clientSessionId:'client-transfer-0001',agentId:'agent-transfer-selftest-0001',deviceId:'dev-transfer-0001'};
