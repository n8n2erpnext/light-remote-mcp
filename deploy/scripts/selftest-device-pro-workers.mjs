import assert from 'node:assert/strict';
import fs from 'node:fs';
import {DeviceWorkerLimiter,planWorkerLimit} from '../../lib/device-worker-limiter.mjs';
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
assert.equal(planWorkerLimit('free',3),1);
assert.equal(planWorkerLimit('pro',5),3);
assert.equal(planWorkerLimit('vip',2),2);
let current=0,peak=0;const completed=[];
const gate=new DeviceWorkerLimiter({limit:()=>3});
const work=(i,ms)=>gate.run(async()=>{current++;peak=Math.max(current,peak);await sleep(ms);current--;completed.push(i);return i;});
const tasks=[work(0,50),work(1,50),work(2,50),work(3,10),work(4,10)];
const results=await Promise.all(tasks);
assert.equal(peak,3);assert.equal(gate.size(),0);assert.deepEqual(results,[0,1,2,3,4]);
const freeGate=new DeviceWorkerLimiter({limit:()=>1});let freeCurrent=0,freePeak=0;
await Promise.all(Array.from({length:5},(_,i)=>freeGate.run(async()=>{freeCurrent++;freePeak=Math.max(freeCurrent,freePeak);await sleep(10);freeCurrent--;return i;})));
assert.equal(freePeak,1);
