import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {toolHelperHint,toolHelperView}=require('../../lib/plus-tool-helper.js');
const root=new URL('../../',import.meta.url),text=file=>fs.readFileSync(new URL(file,root),'utf8');
const hint=toolHelperHint();
assert.equal(hint.action,'tool-helper');
assert.match(hint.instruction,/canonical runtime tool contract/);
const view=toolHelperView({context:{deviceId:'dev1',sessionId:'s_1234567890123456',agentId:'a_1234567890123456',nodeId:'node1',workspace:'/tmp'}});
assert.equal(view.kind,'light-remote-tool-helper');
assert.equal(view.target.deviceId,'dev1');
assert.match(view.transport.payload,/UTF-8 JSON/);
assert.ok(view.tools.fs&&view.tools.search&&view.tools.process&&view.tools.exec&&view.tools.scp&&view.tools.bridgeTransfer&&view.tools.durable);
assert.match(view.tools.scp.when,/binary or large files/i);
for(const op of ['upload-begin','upload-chunk','upload-commit','download-begin','download-chunk','status','cancel'])assert.ok(JSON.stringify(view.tools.scp.ops).includes(op),`missing_scp_op:${op}`);
assert.ok(view.chooseTool.some(row=>row.includes('Do not base64 a file through exec')));
assert.ok(view.tools.scp.recipes.chatAttachmentToDevice&&view.tools.scp.recipes.deviceFileToChat);
assert.ok(view.tools.scp.rules.some(row=>row.includes('effective transport budget')));
assert.equal(view.policy.capabilityBoundary.main,'supported ∩ local policy');
assert.equal(view.policy.capabilityBoundary.fleetLeaf,'supported ∩ server-approved ∩ local policy');
assert.ok(view.safety.some(row=>row.includes('Local policy always retains final deny')));
assert.match(view.tools.bridgeTransfer.rule,/use scp for files/i);
const api=text('api/operator.js'),guide=text('api/guide.js');
assert.ok(api.includes("action==='tool-helper'")&&api.includes("action==='scp'"));
assert.ok(api.includes("'tool-helper','context'")&&api.includes("'search-cancel','scp','transfer-begin'"));
assert.ok(guide.includes('immediately call action=tool-helper')&&guide.includes('Use action=scp'));
console.log('v10-tool-helper=PASS');
console.log('v10-plus-direct-light-scp=PASS');
