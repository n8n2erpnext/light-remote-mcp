import assert from 'node:assert/strict';
import {ProTeamRegistry} from '../../operator-host/pro-team-registry.mjs';
let now=Date.now();
const team=new ProTeamRegistry({now:()=>now,planFor:id=>id==='owner'?'pro':'free',accountActive:()=>true});
team.grantTeamAccess({ownerAccountId:'owner',validUntil:now+30*86400000});
team.create({ownerAccountId:'owner'});
const first=team.invite({ownerAccountId:'owner',memberAccountId:'m1'});
const second=team.invite({ownerAccountId:'owner',memberAccountId:'m1'});
assert.notEqual(first.inviteCode,second.inviteCode);
assert.throws(()=>team.accept({memberAccountId:'m1',inviteCode:first.inviteCode}),/team_invite_invalid/);
for(const member of ['m2','m3','m4'])team.invite({ownerAccountId:'owner',memberAccountId:member});
assert.throws(()=>team.invite({ownerAccountId:'owner',memberAccountId:'m5'}),/team_seat_limit/);
assert.equal(team.invites.size,4,'pending invites must reserve 4 remaining seats');
now+=16*60*1000;
assert.throws(()=>team.accept({memberAccountId:'m1',inviteCode:second.inviteCode}),/team_invite_invalid/);
const renewed=team.invite({ownerAccountId:'owner',memberAccountId:'m5'});
assert(renewed.inviteCode&&team.invites.size===1,'expired invites must be pruned');
console.log('pro_team_invite_rate_budget_capped_by_remaining_seats=PASS');
console.log('pro_team_reinvitation_revokes_old_token=PASS');
console.log('pro_team_expired_invite_pruning=PASS');
