import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(fileURLToPath(new URL('../..',import.meta.url)));
const get=file=>fs.readFileSync(path.join(root,file));
const source=get('client/windows-native/GptOperator.RealRemoteV2/Assets/light-remote-rm.svg');
const copy=get('client/macos/real-remote/Resources/WindowsRMV2.svg');
assert.deepEqual(copy,source,'macOS RM SVG must match Windows RM V2 bytes exactly');
const ico=get('client/windows-native/GptOperator.RealRemoteV2/Assets/light-remote-rm.ico');
const png=get('client/macos/real-remote/Resources/LightRemoteRM-256.png');
const n=ico.readUInt16LE(4);
let match=false;
for(let i=0;i<n;i++){
  const offset=6+i*16;
  const width=ico[offset]||256,height=ico[offset+1]||256;
  if(width!==256||height!==256)continue;
  const len=ico.readUInt32LE(offset+8),start=ico.readUInt32LE(offset+12);
  assert.deepEqual(png,ico.subarray(start,start+len),'RM icon raster must originate unchanged from Windows V2 ICO');
  match=true;break;
}
assert.ok(match,'Windows RM V2 must contain a 256px PNG');
