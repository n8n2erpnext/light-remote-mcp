import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DeviceAccessGrantRegistry, AB_GRANT_MAX_LIFETIME_MS } from '../../operator-host/device-access-grant-registry.mjs';
import { AgentClientRegistry } from '../../operator-host/agent-client-registry.mjs';
import { SessionRegistry } from '../../operator-host/session-manager.mjs';

const H=60*60*1000;
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'lr-ab-24h-'));
let now=1_700_000_000_000;
const clock=()=>now;
const access=new DeviceAccessGrantRegistry({stateFile:path.join(dir,'grants.json'),now:clock});
const clients=new AgentClientRegistry({stateFile:path.join(dir,'clients.json'),now:clock});
const sessions=new SessionRegistry({now:clock});
const accountId='acct_owner',deviceId='dev_owner',connectionId='conn_owner';
const agentId='plugin-aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa';
const foreignAgent='plugin-bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb';
const connectionExpiresAt=now+72*H;
const begin=access.request({accountId,deviceId,connectionId,connectionExpiresAt,agentId,label:'ChatGPT',forceApproval:true});
assert.equal(begin.state,'pending');
const grant=access.approve(begin.request.requestId,{deviceId,connectionId,connectionExpiresAt,idleGraceMs:30*60*1000});
assert.equal(grant.agentId,agentId);
assert.equal(grant.absoluteExpiresAt,now+24*H);
assert.equal(grant.expiresAt,now+24*H);
assert.equal(grant.idleGraceMs,24*H);
const client=clients.attach({accountId,agentId,grant});
assert.equal(client.bindings.length,1);
assert.throws(()=>clients.attach({accountId,agentId:foreignAgent,grant}),/agent_client_grant_agent_mismatch/);
assert.throws(()=>access.assert(grant.grantId,{agentId:foreignAgent}),/device_access_grant_agent_mismatch/);
assert.throws(()=>access.assert(grant.grantId,{accountId:'acct_other'}),/device_access_grant_account_mismatch/);
const foreignRequest=access.request({accountId,deviceId,connectionId,connectionExpiresAt,agentId:foreignAgent});
assert.equal(foreignRequest.state,'pending','another OAuth client must not inherit approval');
const foreignAccountRequest=access.request({accountId:'acct_other',deviceId,connectionId,connectionExpiresAt,agentId});
assert.equal(foreignAccountRequest.state,'pending','another account must not inherit the same agent grant');
const shared=access.request({accountId,deviceId,connectionId,connectionExpiresAt,agentId});
assert.equal(shared.state,'approved','same OAuth client can move between ChatGPT conversations');
assert.equal(shared.grant.grantId,grant.grantId);

const session=sessions.open({accountId,agentId,deviceId,nodeId:'node_owner',gracePreset:'60m'});
assert.throws(()=>sessions.resume(session.sessionId,foreignAgent),/session_owner_mismatch/);
const sameSession=sessions.open({accountId,agentId,deviceId,nodeId:'node_owner',gracePreset:'60m'});
assert.equal(sameSession.sessionId,session.sessionId);

now+=23*H;
assert.equal(access.renewConnection(deviceId,{connectionId,connectionExpiresAt:now+72*H}),1);
assert.equal(access.assert(grant.grantId,{agentId,touch:true}).expiresAt,grant.absoluteExpiresAt);
assert.equal(access.request({accountId,deviceId,connectionId,connectionExpiresAt:now+72*H,agentId}).state,'approved');
now+=H+1;
assert.throws(()=>access.assert(grant.grantId,{agentId}),/device_access_grant_expired/);
assert.equal(access.request({accountId,deviceId,connectionId,connectionExpiresAt:now+72*H,agentId}).state,'pending');

const reapproval=access.request({accountId,deviceId,connectionId,connectionExpiresAt:now+72*H,agentId,forceApproval:true});
const renewed=access.approve(reapproval.request.requestId,{deviceId,connectionId,connectionExpiresAt:now+72*H});
assert.notEqual(renewed.grantId,grant.grantId);
assert.equal(renewed.absoluteExpiresAt,now+24*H);
const oldGrantErr=()=>access.assert(grant.grantId,{agentId});
assert.throws(oldGrantErr,/device_access_grant_required/);
assert.equal(access.assert(renewed.grantId,{agentId}).grantId,renewed.grantId);

const replacementRequest=access.request({accountId,deviceId,connectionId,connectionExpiresAt:now+72*H,agentId,forceApproval:true});
now+=2*60*1000;
const replacement=access.approve(replacementRequest.request.requestId,{deviceId,connectionId,connectionExpiresAt:now+72*H});
assert.notEqual(replacement.grantId,renewed.grantId);
assert.equal(replacement.approvedAt,now);
assert.throws(()=>access.assert(renewed.grantId),/device_access_grant_required/);
assert.equal(access.assert(replacement.grantId,{agentId}).grantId,replacement.grantId);

const file=path.join(dir,'grants.json');
const legacy=JSON.parse(fs.readFileSync(file,'utf8'));
const raw=legacy.grants.find(x=>x.grantId===replacement.grantId);
raw.approvedAt=now-(24*H+1000);raw.expiresAt=now+72*H;delete raw.absoluteExpiresAt;
fs.writeFileSync(file,JSON.stringify(legacy));
const reloaded=new DeviceAccessGrantRegistry({stateFile:file,now:clock});
assert.throws(()=>reloaded.assert(replacement.grantId),/device_access_grant_expired/,'legacy sliding grant must not persist past its original approval');
fs.rmSync(dir,{recursive:true,force:true});
console.log('ab_24h_absolute_expiry=PASS');
console.log('ab_same_oauth_client_cross_chat_resume=PASS');
console.log('ab_other_agent_or_account_denied=PASS');
console.log('ab_connection_renew_does_not_extend_grant=PASS');
console.log('ab_explicit_owner_repair_rotates_grant=PASS');
console.log('ab_legacy_grant_capped_on_reload=PASS');