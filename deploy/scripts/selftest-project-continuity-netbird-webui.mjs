import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import vm from 'node:vm';
// Runs only inside the dedicated Continuity LXD as UAT administrator.
// Never prints or stores the fixture password.
const URL='http://127.0.0.1:5587';
const ownerPassword=fs.readFileSync('/root/light-remote-continuity-uat-fixture.secret','utf8').trim();
const get=(path,cookie)=>fetch(URL+path,{headers:cookie?{cookie}:{},redirect:'manual'});
const first=await get('/projects');
assert.equal(first.status,303);
assert.equal(first.headers.get('location'),'/login');
const noAuth=await get('/api/project-continuity/listProjects');
assert.equal(noAuth.status,401);
const login=await get('/login');
assert.equal(login.status,200);
const loginHtml=await login.text();
const formCsrf=loginHtml.match(/name="csrf" value="([^"]+)"/)?.[1];
assert.ok(formCsrf);
const form=(password)=>new URLSearchParams({csrf:formCsrf,username:'uat-owner',password}).toString();
let response=await fetch(URL+'/auth/login',{method:'POST',headers:{'content-type':'application/x-www-form-urlencoded'},body:form('bad-password'),redirect:'manual'});
assert.equal(response.status,403);
response=await fetch(URL+'/auth/login',{method:'POST',headers:{'content-type':'application/x-www-form-urlencoded'},body:form(ownerPassword),redirect:'manual'});
assert.equal(response.status,303);
const sessionCookie=response.headers.get('set-cookie')?.split(';')[0];
assert.match(sessionCookie,/^lr_wall_session=/);
const projects=await get('/projects',sessionCookie);
assert.equal(projects.status,200);
const html=await projects.text();
assert.match(html,/<title>Light Remote — Projects<\/title>/);
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script);
new vm.Script(script);
const csrf=script.match(/const CSRF="([^"]+)"/)?.[1];
assert.ok(csrf);
const base='/api/project-continuity/';
const post=(action,data,options={})=>fetch(URL+base+action,{
 method:'POST',headers:{cookie:sessionCookie,'content-type':'application/json',
  ...(options.csrf===false?{}:{'x-light-remote-csrf':csrf}),
  ...(options.origin?{origin:options.origin}:{})},
 body:JSON.stringify(data)
});
let invalid=await post('createProject',{name:'Should never be created'},{csrf:false});
assert.equal(invalid.status,403);
invalid=await post('createProject',{name:'Should never be created'},{origin:'https://malicious.example'});
assert.equal(invalid.status,403);
const initial=await get(base+'listProjects',sessionCookie);
assert.equal(initial.status,200);
assert.equal((await initial.json()).ok,true);
const name='NetBird UAT Smoke '+crypto.randomBytes(3).toString('hex');
const created=await post('createProject',{name});
assert.equal(created.status,200);
const data=(await created.json()).result;
assert.equal(data.name,name);
let changed=await post('setModules',{projectId:data.id,memory:true,codex:false,expectedRevision:1});
assert.equal(changed.status,200);
let revision=(await changed.json()).result.revision;
const memo='NETBIRD_WEBUI_UAT_CANARY_'+crypto.randomBytes(6).toString('hex');
const put=await post('memoryPut',{projectId:data.id,body:memo,sourceRef:'owner:uat-web'});
assert.equal(put.status,200);
const checkpoint=await post('checkpoint',{projectId:data.id});
assert.equal(checkpoint.status,200);
const snapshot=(await checkpoint.json()).result;
assert.equal(snapshot.project.memoryEnabled,true);
const context=await post('contextBrief',{projectId:data.id,maxChars:2000,query:memo});
assert.equal(context.status,200);
assert.match((await context.json()).result.content,new RegExp(memo));
invalid=await post('setRemoteReadConsent',{projectId:data.id,enabled:true,expectedRevision:revision,password:'invalid'});
assert.equal(invalid.status,403);
changed=await post('setRemoteReadConsent',{projectId:data.id,enabled:true,expectedRevision:revision,password:ownerPassword});
assert.equal(changed.status,200);
revision=(await changed.json()).result.revision;
changed=await post('setRemoteReadConsent',{projectId:data.id,enabled:false,expectedRevision:revision,password:ownerPassword});
assert.equal(changed.status,200);
assert.equal((await changed.json()).result.remoteReadEnabled,false);
const list=await get(base+'listProjects',sessionCookie);
assert.equal(list.status,200);
const selected=(await list.json()).result.find(p=>p.id===data.id);
assert.equal(selected.remote_read_enabled,0);
