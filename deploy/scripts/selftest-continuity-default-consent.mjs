import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {ContinuityStore} from '../../device-agent/project-continuity-store.mjs';
import {provisionContinuityOwnerAuthority,signContinuityConsent} from '../../device-agent/project-continuity-owner-grants.mjs';
const base=fs.mkdtempSync(path.join(os.tmpdir(),'lr-default-long-memory-'));
const root=path.join(base,'local-client'),signerDir=path.join(base,'owner-credentials');
const password='owner-confirmed-device-account-password-local-fixture';
let db;
try{
 provisionContinuityOwnerAuthority({root,signerDir,password});
 db=new ContinuityStore({root});
 assert.equal(db.projects().length,0);
 let setting=db.moduleSettings();
 setting=db.setGlobalModules({memory:true,codex:false,expectedRevision:setting.revision});
 const id=setting.defaultScopeId;
 assert.equal(db.projects().length,0,'no visible Project');
 db.memoryPut(id,{body:'Gold baseline is the only source; no replacement Wall',sourceRef:'owner:decision'});
 assert.throws(()=>db.remoteBrief(id,{}),/continuity_remote_read_denied/);
 let scope=db.project(id);
 let proof=signContinuityConsent({root,signerDir,password,projectId:id,enabled:true,revision:scope.revision,principal:'gold-account-owner'});
 db.setRemoteReadConsent(id,{proof});
 const brief=db.remoteBrief(id,{maxChars:2000});
 assert.match(brief.content,/Gold baseline/);
 assert.equal(db.projects().length,0);
 db.close();db=null;
 db=new ContinuityStore({root});
 assert.match(db.remoteBrief(id,{maxChars:2000}).content,/Gold baseline/);
 scope=db.project(id);
 proof=signContinuityConsent({root,signerDir,password,projectId:id,enabled:false,revision:scope.revision,principal:'gold-account-owner'});
 db.setRemoteReadConsent(id,{proof});
 assert.throws(()=>db.remoteBrief(id,{}),/continuity_remote_read_denied/);
 setting=db.setGlobalModules({memory:false,codex:false,expectedRevision:db.moduleSettings().revision});
 assert.equal(setting.memoryEnabled,false);
 assert.throws(()=>db.memorySearch(id,'Gold'),/continuity_memory_disabled/);
 console.log('DEFAULT_LONG_MEMORY_NO_PROJECT_SIGNED_OWNER_REMOTE_RECALL_PASS');
 console.log('DEFAULT_LONG_MEMORY_OWNER_REVOKE_AND_OFF_OFF_FAIL_CLOSED_PASS');
}finally{try{db?.close();}catch{}fs.rmSync(base,{recursive:true,force:true});}
